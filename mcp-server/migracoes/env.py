"""Alembic com o motor assíncrono da aplicação. A URL vem de `sqlalchemy.url` (quem chama de
código passa) ou do DATABASE_URL das configurações."""
import asyncio

from alembic import context
from sqlalchemy.ext.asyncio import create_async_engine

from app.dados import modelos  # noqa: F401 - registra as tabelas no metadata
from app.dados.banco import Base

config = context.config
target_metadata = Base.metadata


def _url() -> str:
    url = config.get_main_option("sqlalchemy.url")
    if url:
        return url
    from app.config import get_settings

    return get_settings().database_url


def _run(connection) -> None:
    context.configure(connection=connection, target_metadata=target_metadata, compare_type=True,
                      render_as_batch=connection.dialect.name == "sqlite")
    with context.begin_transaction():
        context.run_migrations()


async def _online() -> None:
    engine = create_async_engine(_url())
    async with engine.connect() as connection:
        await connection.run_sync(_run)
    await engine.dispose()


if context.is_offline_mode():
    context.configure(url=_url(), target_metadata=target_metadata, literal_binds=True)
    with context.begin_transaction():
        context.run_migrations()
else:
    asyncio.run(_online())
